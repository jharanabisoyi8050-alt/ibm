"""
Page 3 - Traffic Density & Congestion Monitor
Real-time (simulated) traffic monitoring with multi-zone analysis
"""
import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px
import plotly.graph_objects as go
from datetime import datetime

st.set_page_config(page_title="Traffic Monitor | Road Safety AI", page_icon="🚗", layout="wide")

st.title("🚗 Traffic Density & Congestion Monitor")
st.caption("Live traffic density visualization. **Traffic Agent** (Google Gemini Flash) + simulated MCP traffic tools.")
st.warning("⚠️ **SIMULATED DATA**: Traffic data is generated by the simulator. `is_simulated=True` on all records.", icon="⚠️")

# ── Location Selector ─────────────────────────────────────────────────────────
with st.expander("📍 Select Analysis Location", expanded=True):
    col1, col2, col3 = st.columns(3)
    with col1:
        lat = st.number_input("Latitude", value=51.5074, format="%.4f")
    with col2:
        lng = st.number_input("Longitude", value=-0.1278, format="%.4f")
    with col3:
        radius_km = st.slider("Analysis Radius (km)", 1.0, 20.0, 5.0)

    analyze = st.button("🔍 Analyze Traffic", type="primary", use_container_width=True)

# ── Simulated traffic analysis ────────────────────────────────────────────────
np.random.seed(int(abs(lat * lng * 100)) % 9999)

density = round(np.random.uniform(40, 95), 1)
speed = round(np.random.uniform(15, 75), 1)
vehicle_count = np.random.randint(80, 320)
congestion = (
    "SEVERE" if density > 85 else
    "HIGH" if density > 70 else
    "MODERATE" if density > 45 else
    "LOW"
)
cong_color = {"LOW": "green", "MODERATE": "orange", "HIGH": "red", "SEVERE": "darkred"}

# ── KPIs ──────────────────────────────────────────────────────────────────────
st.subheader("📡 Current Traffic Status")
k1, k2, k3, k4 = st.columns(4)
k1.metric("Traffic Density", f"{density}%", "SIMULATED")
k2.metric("Avg Speed", f"{speed} km/h")
k3.metric("Vehicle Count", f"{vehicle_count}", "SIMULATED")
k4.metric("Congestion Level", congestion, delta_color="off")

# Color the congestion metric
if congestion in ["HIGH", "SEVERE"]:
    st.error(f"🔴 **{congestion} congestion** detected in this zone. AI agents are monitoring.")
elif congestion == "MODERATE":
    st.warning(f"🟠 **{congestion} congestion** — elevated accident risk possible.")
else:
    st.success(f"🟢 **{congestion} traffic** — normal conditions.")

st.divider()

# ── 24h trend chart ───────────────────────────────────────────────────────────
col_a, col_b = st.columns(2)

with col_a:
    st.subheader("📈 24-Hour Density Trend")
    hours = list(range(24))
    base = [15, 12, 10, 9, 12, 25, 65, 88, 85, 72, 65, 60,
            58, 62, 70, 82, 91, 85, 70, 55, 42, 35, 25, 18]
    noise = np.random.normal(0, 5, 24)
    trend = np.clip(np.array(base) + noise, 0, 100)
    df_trend = pd.DataFrame({
        "Hour": [f"{h:02d}:00" for h in hours],
        "Density (%)": trend,
        "Speed (km/h)": np.clip(80 - trend * 0.7 + np.random.normal(0, 3, 24), 5, 90),
    })
    fig = px.line(df_trend, x="Hour", y=["Density (%)", "Speed (km/h)"],
                  color_discrete_map={"Density (%)": "#dc2626", "Speed (km/h)": "#3b82d4"})
    fig.update_layout(height=320, plot_bgcolor="#f7f8fa", margin=dict(t=10))
    st.plotly_chart(fig, use_container_width=True)

with col_b:
    st.subheader("🗺️ Traffic Density Scatter Map")
    np.random.seed(42)
    n = 100
    df_map = pd.DataFrame({
        "lat": np.random.uniform(lat - radius_km / 111, lat + radius_km / 111, n),
        "lon": np.random.uniform(lng - radius_km / 111, lng + radius_km / 111, n),
        "density": np.random.uniform(10, 100, n),
    })
    df_map["congestion"] = pd.cut(
        df_map["density"], bins=[0, 45, 70, 85, 100],
        labels=["LOW", "MODERATE", "HIGH", "SEVERE"]
    )
    fig_map = px.scatter_mapbox(
        df_map, lat="lat", lon="lon", color="congestion",
        color_discrete_map={"LOW": "#16a34a", "MODERATE": "#d97706",
                             "HIGH": "#ea580c", "SEVERE": "#dc2626"},
        size="density", size_max=15, zoom=11,
        mapbox_style="open-street-map", height=320,
    )
    fig_map.update_layout(margin=dict(t=0, b=0))
    st.plotly_chart(fig_map, use_container_width=True)

# ── Zone breakdown table ──────────────────────────────────────────────────────
st.subheader("📋 Traffic Records by Zone")
zones_data = pd.DataFrame({
    "Zone": ["North", "South", "East", "West", "Central", "Ring Road", "Highway A1"],
    "Density (%)": np.random.uniform(20, 95, 7).round(1),
    "Avg Speed (km/h)": np.random.uniform(15, 75, 7).round(1),
    "Vehicle Count": np.random.randint(50, 350, 7),
    "Congestion": np.random.choice(["LOW", "MODERATE", "HIGH", "SEVERE"], 7),
    "is_simulated": [True] * 7,
    "Timestamp": [datetime.utcnow().strftime("%Y-%m-%d %H:%M") for _ in range(7)],
})

def color_congestion(val):
    c = {"SEVERE": "background-color:#fecaca;font-weight:bold",
         "HIGH": "background-color:#fed7aa;font-weight:bold",
         "MODERATE": "background-color:#fef3c7",
         "LOW": "background-color:#dcfce7"}
    return c.get(val, "")

st.dataframe(
    zones_data.style.applymap(color_congestion, subset=["Congestion"]),
    use_container_width=True, hide_index=True,
)

# ── Agent output ──────────────────────────────────────────────────────────────
with st.expander("🤖 Traffic Agent Raw Output (Gemini Flash)", expanded=False):
    st.code(f"""{{
  "agent": "traffic_agent",
  "model": "gemini-2.0-flash",
  "location": {{"lat": {lat}, "lng": {lng}}},
  "density_score": {density},
  "avg_speed_kmh": {speed},
  "vehicle_count": {vehicle_count},
  "congestion_level": "{congestion}",
  "is_simulated": true,
  "data_source": "SIMULATED_FEED",
  "timestamp": "{datetime.utcnow().isoformat()}"
}}""", language="json")

st.divider()
st.caption("Traffic data is simulated for demonstration. Replace `is_simulated=True` records with live HERE Maps or TomTom API in production.")
